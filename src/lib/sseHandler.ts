import { Request, Response } from "express";
import { Server } from "@modelcontextprotocol/sdk/server/index.js";
import { SSEServerTransport } from "@modelcontextprotocol/sdk/server/sse.js";
import { sessionRegistry } from "./sessionRegistry.js";

export async function handleSSEConnection(
  server: Server,
  req: Request,
  res: Response
): Promise<void> {
  // Determine message endpoint from request path
  // /gitlab/sse -> /gitlab/message
  // /sonarqube/sse -> /sonarqube/message
  const messagePath = req.path.replace(/\/sse$/, "/message");

  // Create SSE transport
  const transport = new SSEServerTransport(messagePath, res);

  try {
    await server.connect(transport);

    // Extract sessionId from the transport
    // The sessionId is generated by the transport and sent to the client
    const sessionId = (transport as any).sessionId;

    if (sessionId) {
      // Register the transport for message routing
      sessionRegistry.register(sessionId, transport);
      console.log(`SSE connection established for ${req.path}, sessionId: ${sessionId}`);

      // Handle client disconnect - cleanup the session
      req.on("close", () => {
        console.log(`SSE connection closed for ${req.path}, sessionId: ${sessionId}`);
        sessionRegistry.remove(sessionId);
      });
    } else {
      console.warn(`SSE transport created without sessionId for ${req.path}`);
    }
  } catch (error) {
    console.error(`Failed to establish SSE connection for ${req.path}:`, error);

    if (!res.headersSent) {
      res.status(500).json({
        error: "Failed to establish SSE connection",
        path: req.path,
      });
    }
  }
}
